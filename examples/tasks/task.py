"""A finite producer/consumer example; ordering comes from devd's task gate."""
from pathlib import Path
import sys
import time


def main():
    output = Path("generated.txt")
    if sys.argv[1] == "generate":
        time.sleep(0.2)
        output.write_text("generated by the completed task\n", encoding="utf-8")
        print("generation finished", flush=True)
    elif sys.argv[1] == "consume":
        print(output.read_text(encoding="utf-8").strip(), flush=True)
    else:
        raise SystemExit("expected generate or consume")


if __name__ == "__main__":
    main()
